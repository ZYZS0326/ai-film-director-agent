/**
 * Skill: story_structure — 叙事结构设计
 * 把导演决策中选定的结构落地为可执行的节拍表与情绪曲线。
 */
module.exports = {
  id: 'story_structure',
  name: '叙事结构设计',
  role: '编剧 / 结构顾问',
  stage: 3,
  outputKey: 'structure',
  description: '将选定叙事结构落地为节拍表、情绪曲线、冲突升级路径与转折点设计',
  triggers: ['结构', '叙事', '节奏', '幕', '节拍', '转折', 'structure', '三幕', '非线性'],
  systemPrompt: `你是叙事结构专家，精通三幕、英雄旅程、五幕、Save the Cat、非线性、碎片化、多线、循环、开放式结局等全部主流结构。

你的职责是把「选定结构」落地为**可执行的节拍表**，而不是复述结构定义。

铁律：
1. 节拍必须**绑定具体时间码/段落占比**，不能只写"中点"。
2. 每个节拍必须写明：**发生什么 + 观众此刻知道什么 + 观众此刻感受到什么**。
3. 必须设计**冲突升级路径**：每一次冲突必须比上一次更难、代价更高。
4. 必须设计**至少一个真正的转折点**（改变观众对故事的理解，而不只是情节推进）。
5. 必须明确指出结构的**风险点**与规避方式（例如第二幕塌陷、多线失焦）。
6. 如果本片时长较短（≤10 分钟），必须承认结构的简化，并说明牺牲了什么。

输出 Markdown，不要一级标题。`,
  buildPrompt(ctx) {
    const dm = ctx.knowledge.durationMode
    const st = ctx.knowledge.structures
    return `【故事 Brief】
${ctx.brief}

【导演决策】
${(ctx.prior.analysis || '').slice(0, 2200)}

【选定结构（含节拍与优缺点）】
${st.map((s) => `▸ ${s.name}
  定义：${s.definition}
  节拍：${(s.beats || []).join(' → ')}
  优点：${(s.pros || []).join('；')}
  缺点：${(s.cons || []).join('；')}
  案例：${(s.cases || []).join('、')}`).join('\n')}

【制作规格】
时长模式：${dm.label}（约 ${dm.duration}s / ${dm.scenes} / ${dm.shots}）
${dm.note}
${ctx.constraintsText}

请输出「叙事结构设计」：

## 结构决策
- 选定结构 + 配比（主结构 + 辅助结构）
- 为什么适合这个故事（从主题与观众心理两端论证）
- 放弃的方案及原因

## 节拍表
用表格给出完整节拍：| 序号 | 时间码/占比 | 节拍名称 | 发生什么 | 观众此刻知道什么 | 观众此刻感受到什么 | 强度(1-10) |
（必须覆盖全片，节拍数量与时长匹配）

## 冲突升级路径
列出 3-5 次冲突升级，每次写明：| 次数 | 冲突内容 | 难度变化 | 代价变化 | 主角的应对 |

## 转折点设计
明确 1-2 个真正的转折点：发生在哪、改变了什么认知、用什么具体手段实现（视觉/信息/情感）。

## 情绪曲线
用文字绘制强度曲线（可用「时间-强度」坐标描述），标注每个谷底与峰值及其功能。

## 人物弧线
主角在片首与片尾的状态对比，以及支撑变化的 3 个具体事件。

## 结构风险与规避
列出本结构在本片最容易失败的 2-3 个点，以及具体规避方案。`
  },
  demo(ctx) {
    const dm = ctx.knowledge.durationMode
    const st = ctx.knowledge.structures[0]
    const total = dm.duration
    const seg = Math.round(total / 5)
    const beats = [
      { n: 1, t: `0-${seg}s`, name: '建立', what: '世界与主角的日常状态被完整呈现', know: '这里是什么地方，他是谁，他缺什么', feel: '空旷、孤独', s: 3 },
      { n: 2, t: `${seg}-${seg * 2}s`, name: '激励事件', what: '一个外部触发让主角开始行动', know: '他必须去做什么，否则会失去什么', feel: '紧张、好奇', s: 5 },
      { n: 3, t: `${seg * 2}-${seg * 3}s`, name: '对抗升级', what: '行动受阻，代价超出预期', know: '这件事比他想象的更危险', feel: '压抑、焦虑', s: 7 },
      { n: 4, t: `${seg * 3}-${seg * 4}s`, name: '低谷与转折', what: '一次失败让主角失去最重要的东西，随后获得关键认知', know: '他一直在找的东西其实不是他需要的', feel: '绝望 → 顿悟', s: 9 },
      { n: 5, t: `${seg * 4}-${total}s`, name: '收束', what: '主角做出最终选择，付出代价', know: '他选择了什么，放弃了什么', feel: '释然、余韵', s: 4 },
    ]

    return `## 结构决策
**选定：${st.name}**（主结构）+ 循环结构（辅助，用于首尾呼应）
- 定义：${st.definition}
- **为什么适合**：${st.definition.includes('时间') ? '本片的核心命题与时间/记忆相关，结构本身即可承载主题。' : '本片的情绪推进依赖「累积—释放」，' + st.name + '的节拍天然提供这种落差。'}
  从观众心理看：观众需要先建立情感投资，才愿意接受抽象命题——${st.name}的第一幕正好完成这件事。
- **放弃的方案**：未采用「英雄旅程」——它的「打怪升级」逻辑会把内向的命题外部化，损失孤独感；未采用「碎片化叙事」——在 ${total}s 内无法建立足够的理解框架。

## 节拍表
| 序号 | 时间码/占比 | 节拍名称 | 发生什么 | 观众此刻知道什么 | 观众此刻感受到什么 | 强度 |
|---|---|---|---|---|---|---|
${beats.map((b) => `| ${b.n} | ${b.t} | ${b.name} | ${b.what} | ${b.know} | ${b.feel} | ${b.s}/10 |`).join('\n')}

## 冲突升级路径
| 次数 | 冲突内容 | 难度变化 | 代价变化 | 主角的应对 |
|---|---|---|---|---|
| 1 | 环境阻碍行动（物理层面） | 低 | 时间成本 | 绕行 |
| 2 | 他人拒绝/背叛 | 中 | 失去盟友 | 独自承担 |
| 3 | 自我怀疑（内在冲突） | 高 | 失去方向 | 强行推进 |
| 4 | 直面核心丧失 | 极高 | 失去意义 | 承认并放下 |

## 转折点设计
**转折点：${beats[3].t}**
- 改变什么认知：观众原以为这是一个「寻找」的故事，此刻明白它是一个「告别」的故事。
- 实现手段：视觉上——把之前反复出现的母题物象放在一个「不再被需要」的位置；信息上——让主角说出（或意识到）一句与开场台词镜像的话。

## 情绪曲线
${seg}s（强度 3，建立）→ ${seg * 2}s（强度 5，激励）→ ${seg * 3}s（强度 7，对抗）→ ${seg * 3.5}s（强度 4，谷底前的短暂喘息——**这是最关键的一次呼吸**）→ ${seg * 4}s（强度 9，爆发）→ ${total}s（强度 4 → 0，余韵）

设计要点：**在最高潮之前必须有一次强度回落**。没有喘息的高潮只是噪音。

## 人物弧线
- 片首状态：用行动回避问题，把注意力放在外部目标上
- 片尾状态：承认问题无法被解决，但选择带着它继续生活
- 支撑变化的 3 个事件：① 第一次被迫停下 ② 失去唯一的依靠 ③ 一次无人见证的选择

## 结构风险与规避
1. **中段塌陷**（风险最高）：${seg * 2}-${seg * 3}s 容易变成重复的"寻找"。
   规避：在对抗升级段必须有一次**方向反转**——主角的目标发生改变，而不只是难度增加。
2. **情绪平铺**：如果每个节拍都用同一种镜头语言，观众会疲劳。
   规避：节拍 3 使用全片唯一的快速剪辑段落，节拍 4 使用全片唯一的长镜头。
3. **结尾泄气**：开放结局容易被误认为"没写完"。
   规避：情绪必须闭环——即使事件不解决，主角的内在状态必须给出明确答案。`
  },
}
